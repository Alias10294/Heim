#!/usr/bin/env python3
"""Generate Heim amalgamated public headers from include/heim (Python >= 3.10).

Usage:
    python scripts/generate_single_include.py
    python scripts/generate_single_include.py --check

Source headers are authoritative. Generated files are committed, never edited.
"""

from __future__ import annotations

import argparse
import difflib
import os
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]
INCLUDE_ROOT = ROOT / 'include'
OUTPUT_ROOT = ROOT / 'single_include'
ENTRYPOINTS = (
    'heim/graph.hpp',
    'heim/heim.hpp',
    'heim/property.hpp'
)

# Only literal includes are accepted: macro-generated includes would require
# a C++ preprocessor and cannot be safely amalgamated by textual substitution.
INCLUDE = re.compile(r'^\s*#\s*include\s*([<"])([^>"]+)[>"]\s*(?://.*|/\*.*\*/\s*)?$')
DIRECTIVE = re.compile(r'^\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b')


class GenerationError(RuntimeError):
    pass


class Amalgamator:
    def __init__(self, include_root: Path):
        self.include_root = include_root.resolve()
        self.emitted: set[Path] = set()
        self.stack: list[Path] = []

    def _resolve(self, including: Path, spelling: str, delimiter: str) -> Path | None:
        # All angle-bracket includes outside the heim/ namespace remain external.
        if delimiter == '<' and not spelling.startswith('heim/'):
            return None
        candidates = [including.parent / spelling, self.include_root / spelling]
        for candidate in candidates:
            candidate = candidate.resolve()
            if candidate.is_relative_to(self.include_root) and candidate.is_file():
                return candidate
        if delimiter == '"' or spelling.startswith('heim/'):
            relative = including.relative_to(self.include_root)
            raise GenerationError(f'{relative}: unresolved local include {spelling!r}')
        return None

    def expand(self, file: Path) -> str:
        file = file.resolve()
        if not file.is_relative_to(self.include_root) or not file.is_file():
            raise GenerationError(f'Not a source header: {file}')
        # Heim sources are guard-protected. Emit each header just once. An
        # inclusion cycle is therefore equivalent to a guard-protected skip.
        if file in self.emitted:
            return ''
        self.emitted.add(file)
        self.stack.append(file)
        relative = file.relative_to(self.include_root).as_posix()
        lines = file.read_text(encoding='utf-8-sig').splitlines(keepends=True)
        output = [f'// >>> BEGIN {relative}\n']
        depth = 0
        for number, line in enumerate(lines, start=1):
            stripped = line.rstrip('\r\n')
            directive = DIRECTIVE.match(stripped)
            match = INCLUDE.fullmatch(stripped)
            if match:
                delimiter, spelling = match.groups()
                target = self._resolve(file, spelling, delimiter)
                if target is not None:
                    # Unconditionally inlining an include inside a conditional
                    # branch can suppress a needed subsequent include. A normal
                    # header guard, at nesting depth 1, is the sole exception.
                    if depth > 1:
                        raise GenerationError(
                            f'{relative}:{number}: local include under nested #if; '
                            'conditional amalgamation needs explicit handling')
                    output.append(self.expand(target))
                    continue
            elif re.match(r'^\s*#\s*include\b', stripped):
                raise GenerationError(f'{relative}:{number}: unsupported include syntax: {stripped}')

            # A #pragma once inside an amalgamation refers to the generated
            # physical file, not to the original nested header.
            if re.match(r'^\s*#\s*pragma\s+once\s*$', stripped):
                continue
            output.append(line if line.endswith('\n') else line + '\n')
            if directive:
                kind = directive.group(1)
                if kind in ('if', 'ifdef', 'ifndef'):
                    depth += 1
                elif kind == 'endif':
                    depth -= 1
                    if depth < 0:
                        raise GenerationError(f'{relative}:{number}: unmatched #endif')
        if depth != 0:
            raise GenerationError(f'{relative}: unbalanced preprocessor conditionals')
        self.stack.pop()
        output.append(f'// <<< END {relative}\n')
        return ''.join(output)

    def generate(self, entrypoint: Path) -> str:
        self.emitted.clear()
        self.stack.clear()
        relative = entrypoint.relative_to(self.include_root).as_posix()
        banner = (
            '// Generated by scripts/generate_single_include.py. DO NOT EDIT.\n'
            f'// Source: include/{relative}\n'
            '// Distributed under the terms of the Heim project license.\n\n'
        )
        return banner + self.expand(entrypoint)


def run(check: bool) -> int:
    failures = 0
    for name in ENTRYPOINTS:
        source = INCLUDE_ROOT / name
        dest = OUTPUT_ROOT / name
        content = Amalgamator(INCLUDE_ROOT).generate(source)
        current = dest.read_text(encoding='utf-8-sig') if dest.exists() else None
        if current == content:
            print(f'OK: {dest.relative_to(ROOT)}')
            continue
        if check:
            failures += 1
            print(f'OUTDATED: {dest.relative_to(ROOT)}')
            if current is not None:
                diff = difflib.unified_diff(
                    current.splitlines(), content.splitlines(),
                    fromfile=str(dest), tofile='expected', lineterm='')
                for line in list(diff)[:30]:
                    print(line)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        # Atomic replacement reduces the risk of partially written headers.
        fd, temp = tempfile.mkstemp(prefix='.heim-', suffix='.hpp', dir=dest.parent)
        try:
            with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
                stream.write(content)
            os.replace(temp, dest)
        finally:
            if os.path.exists(temp):
                os.unlink(temp)
        print(f'UPDATED: {dest.relative_to(ROOT)}')
    return int(failures != 0)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated files without modifying them')
    args = parser.parse_args()
    try:
        return run(args.check)
    except (GenerationError, OSError, UnicodeError) as exc:
        parser.exit(2, f'Generation failed: {exc}\n')


if __name__ == '__main__':
    raise SystemExit(main())
